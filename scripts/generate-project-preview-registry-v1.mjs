#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const PROJECTS = path.join(ROOT, 'projects');
const OUTPUT = path.join(ROOT, 'src', 'generated-project-preview-registry-v1.js');

const clean = (value, max = 1000) => String(value ?? '').trim().slice(0, max);
const safeToken = (value) => {
  const raw = clean(value, 320);
  return raw && /^[a-z0-9._:+-]+$/i.test(raw) ? raw : null;
};

async function readJson(file) {
  try { return JSON.parse(await readFile(file, 'utf8')); } catch { return null; }
}

function projectMeta(raw = {}, dirName = '') {
  raw = raw && typeof raw === 'object' ? raw : {};
  const nested = raw?.project && typeof raw.project === 'object' ? raw.project : {};
  const workspace = raw?.operator_workspace && typeof raw.operator_workspace === 'object' ? raw.operator_workspace : {};
  const projectId = safeToken(raw.project_id)
    || safeToken(nested.project_id)
    || safeToken(workspace.project_id)
    || safeToken(nested.slug)
    || safeToken(dirName);
  const customerId = safeToken(raw.customer_id) || safeToken(nested.customer_id) || null;
  const scopeKey = clean(raw.scope_key || nested.scope_key, 640) || null;
  const name = clean(raw.name || nested.name || raw.business_name || dirName, 240) || dirName;
  return { project_id: projectId, customer_id: customerId, scope_key: scopeKey, name };
}

function htmlPriority(name = '') {
  const lower = name.toLowerCase();
  if (lower === 'ferrari-preview-v1.html') return 0;
  if (lower === 'index.html') return 1;
  if (lower.includes('preview') && lower.endsWith('.html')) return 2;
  if (lower.endsWith('.html') && lower !== '404.html') return 3;
  return 99;
}

async function inlineLocalStyles(projectDir, html) {
  const tags = [...html.matchAll(/<link\b[^>]*>/gi)];
  let output = html;
  let inlined = 0;
  for (const match of tags) {
    const tag = match[0];
    const rel = tag.match(/\brel\s*=\s*["']([^"']+)["']/i)?.[1] || '';
    const href = tag.match(/\bhref\s*=\s*["']([^"']+)["']/i)?.[1] || '';
    if (!/\bstylesheet\b/i.test(rel) || !href) continue;
    if (/^(?:https?:|\/\/|data:|\/)/i.test(href)) continue;
    const relative = href.replace(/^\.\//, '').split(/[?#]/)[0];
    if (!relative || relative.includes('..')) continue;
    const cssPath = path.resolve(projectDir, relative);
    if (!cssPath.startsWith(projectDir + path.sep)) continue;
    let css;
    try { css = await readFile(cssPath, 'utf8'); } catch { continue; }
    const safeCss = css.replace(/<\/style/gi, '<\\/style');
    output = output.replace(tag, `<style data-aurentara-preview-bundled-css="${relative.replace(/"/g, '&quot;')}">\n${safeCss}\n</style>`);
    inlined += 1;
  }
  return { html: output, styles_inlined: inlined };
}

async function buildRegistry() {
  const dirs = (await readdir(PROJECTS, { withFileTypes: true }))
    .filter((item) => item.isDirectory())
    .map((item) => item.name)
    .sort();

  const entries = [];
  for (const dirName of dirs) {
    const projectDir = path.join(PROJECTS, dirName);
    const files = (await readdir(projectDir, { withFileTypes: true }))
      .filter((item) => item.isFile())
      .map((item) => item.name);
    const htmlName = files
      .filter((name) => /\.html?$/i.test(name))
      .sort((a, b) => htmlPriority(a) - htmlPriority(b) || a.localeCompare(b))[0];
    if (!htmlName || htmlPriority(htmlName) >= 99) continue;

    const meta = projectMeta(await readJson(path.join(projectDir, 'project.json')), dirName);
    const sourcePath = `projects/${dirName}/${htmlName}`;
    const rawHtml = await readFile(path.join(projectDir, htmlName), 'utf8');
    const bundled = await inlineLocalStyles(projectDir, rawHtml);
    const contentHash = createHash('sha256').update(bundled.html).digest('hex');

    entries.push({
      registry_key: dirName,
      project_dir: dirName,
      project_id: meta.project_id,
      customer_id: meta.customer_id,
      scope_key: meta.scope_key,
      name: meta.name,
      source_path: sourcePath,
      html: bundled.html,
      styles_inlined: bundled.styles_inlined,
      content_hash: contentHash,
      media_type: 'text/html; charset=utf-8'
    });
  }
  return entries;
}

const entries = await buildRegistry();
const source = `// AUTO-GENERATED by scripts/generate-project-preview-registry-v1.mjs. DO NOT EDIT.\n`
  + `export const GENERATED_PROJECT_PREVIEW_REGISTRY_V1 = Object.freeze(${JSON.stringify(entries, null, 2)});\n\n`
  + `export function generatedProjectPreviewRegistryManifest() {\n`
  + `  return Object.freeze({ schema: 'aurentara.generated-project-preview-registry.v1', project_count: GENERATED_PROJECT_PREVIEW_REGISTRY_V1.length, build_time_generated: true, runtime_network_dependency: false, project_specific_exceptions: false, production_deploy: false });\n`
  + `}\n`;

await writeFile(OUTPUT, source, 'utf8');
process.stdout.write(JSON.stringify({
  ok: true,
  output: path.relative(ROOT, OUTPUT).replaceAll(path.sep, '/'),
  project_count: entries.length,
  projects: entries.map((entry) => ({ registry_key: entry.registry_key, project_id: entry.project_id, scope_key: entry.scope_key, source_path: entry.source_path, styles_inlined: entry.styles_inlined })),
  production_deploy: false
}, null, 2) + '\n');
