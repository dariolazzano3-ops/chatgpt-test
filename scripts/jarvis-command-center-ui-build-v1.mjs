/* Build the accepted JARVIS Command Center (orange/amber) into a single
   self-contained browser bundle and vendor it as
   src/jarvis/command-center-ui/bundle.built.js so the private worker can
   serve it inline (no deploy-time asset pipeline, CSP 'unsafe-inline').

   Source of truth for the visual design:
     src/jarvis/command-center-ui/jarvis-command-center.jsx  (VISUAL_BASELINE=ACCEPTED)
   Only its System Status section is wired to GET <apiBase>/runtime-truth. */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { build } from "esbuild";

const ROOT = path.resolve(".");
const ENTRY = "src/jarvis/command-center-ui/entry.jsx";
const OUT = path.join(ROOT, "src/jarvis/command-center-ui/bundle.built.js");

/* Markers copied verbatim from the accepted source. If the bundle no longer
   contains these, the served UI is not the accepted orange Command Center. */
const ACCEPTED_MARKERS = [
  "--amber:#ffab40",
  "--bg:#040405",
  "--hi:#ffd08a",
  "--deep:#ff7a1a",
  "'Michroma'",
  ".jcc",
  "bg-glow",
  "Command Center",
  "Denken. Bauen.",
  "Systemstatus",
];
/* Must be present because System Status is wired to runtime truth. */
const RUNTIME_TRUTH_MARKERS = ["/runtime-truth", "Nicht verbunden", "classification"];
/* The legacy blue UI must never be able to satisfy the acceptance test, and the
   fake per-service operational metrics must not ship in the System Status data. */
const FORBIDDEN = [
  "A BRIGHTER YOU", "PERSONAL AI OS", "--blue:#8bd2ff", "/jarvis/api/",
  // fake per-service System Status metrics that were removed from SERVICES
  "38 ms", "64 ms", "210 ms", "99,98 %", "99,91 %", "99,80 %", "1 von 2 Slots",
  // Wave 4: seeded mock Runs / Activity / Approvals removed from init()
  "Command Center V1: Home-Ansicht", "Nightly: Dependency-Audit aller Repos",
  "AURENTARA: Landing-Copy veröffentlichen", "HAMYREN: Staging-Deploy",
  "main@a3f9e21", "94 %", "+11 diese Woche", "Evidence-Paket E-3812 signiert",
  "Wartet auf Freigabe A-031",
];

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  minify: true,
  charset: "utf8",
  legalComments: "none",
  sourcemap: false,
  write: false,
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
});

let code = result.outputFiles[0].text;

for (const marker of [...ACCEPTED_MARKERS, ...RUNTIME_TRUTH_MARKERS]) {
  if (!code.includes(marker)) {
    throw new Error(`JARVIS_CC_BUNDLE_MISSING_MARKER: ${JSON.stringify(marker)}`);
  }
}
for (const bad of FORBIDDEN) {
  if (code.includes(bad)) {
    throw new Error(`JARVIS_CC_BUNDLE_FORBIDDEN_STRING: ${JSON.stringify(bad)}`);
  }
}

// Safe to embed inside an inline <script> in the server shell.
code = code.replace(/<\/script/gi, "<\\/script");

const sha256 = crypto.createHash("sha256").update(code).digest("hex");
const bytes = Buffer.byteLength(code, "utf8");

const file = `/* GENERATED by scripts/jarvis-command-center-ui-build-v1.mjs — DO NOT EDIT.
   Accepted JARVIS Command Center (jarvis-command-center.jsx), bundled with
   React + lucide-react for inline delivery by the private worker.
   Rebuild: npm run jarvis:command-center:build */
export const JARVIS_COMMAND_CENTER_BUNDLE_V1 = ${JSON.stringify(code)};
export const JARVIS_COMMAND_CENTER_BUNDLE_SHA256_V1 = ${JSON.stringify(sha256)};
export const JARVIS_COMMAND_CENTER_BUNDLE_BYTES_V1 = ${bytes};
`;

fs.writeFileSync(OUT, file, "utf8");
console.log(`JARVIS Command Center UI build: PASS (${(bytes / 1024).toFixed(1)} KiB, sha256 ${sha256.slice(0, 12)}…)`);
